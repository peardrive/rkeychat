// Copy rKeyChat's source (../src) into ./core so it resolves this package's
// Bare dependencies. core/ is generated: edit ../src, then re-run.
import fs from 'fs'
import path from 'path'
const from = path.join(import.meta.dirname ?? path.dirname(new URL(import.meta.url).pathname), '..', 'src')
const to = path.join(path.dirname(new URL(import.meta.url).pathname), 'core')
fs.rmSync(to, { recursive: true, force: true })
const copy = (a, b) => {
  fs.mkdirSync(b, { recursive: true })
  for (const e of fs.readdirSync(a, { withFileTypes: true })) {
    const s = path.join(a, e.name); const d = path.join(b, e.name)
    e.isDirectory() ? copy(s, d) : fs.copyFileSync(s, d)
  }
}
copy(from, to)
// The ACP bridge (src/acp.js) drives Claude Code through a child process and the ACP SDK: a computer's job. The
// phone never hosts a seat, so its copy is a stub with the same exports; the daemon only reaches it when a
// project agent is woken, which cannot happen here (the phone is never a project's home).
fs.writeFileSync(path.join(to, 'acp.js'), `// generated by sync-core.js: no ACP on the phone
export const ASK_TIMEOUT_MS = 10 * 60_000
export class AcpProcess { constructor () { throw new Error('agents run on a computer, not on this device') } }
export function permitted () { return false }
export function verdict () { return 'deny' }
export function adapterPath () { return null }
export function nodeEnv (env) { return env }
`)
// the stub must offer every name the rest of the daemon imports from './acp.js', or the phone dies at start
// (2026-11-22: "does not provide an export named 'ASK_TIMEOUT_MS'")
const stubbed = new Set(['ASK_TIMEOUT_MS', 'AcpProcess', 'permitted', 'verdict', 'adapterPath', 'nodeEnv'])
for (const f of fs.readdirSync(to).filter((n) => n.endsWith('.js') && n !== 'acp.js')) {
  const src = fs.readFileSync(path.join(to, f), 'utf8')
  for (const m of src.matchAll(/import\s*\{([^}]*)\}\s*from\s*'\.\/acp\.js'/g)) {
    for (const name of m[1].split(',').map((x) => x.trim().split(/\s+as\s+/)[0]).filter(Boolean)) {
      if (!stubbed.has(name)) throw new Error(`${f} imports ${name} from ./acp.js, which the phone's stub does not export: add it to sync-core.js`)
    }
  }
}
console.log('synced', from, '->', to, '(acp.js stubbed)')
