// (Node) Embed the files the backend reads from disk (the web UI, pearcore's
// SQL migrations, and the new shell's build when it exists) into assets.js, so a
// bundled app can write them out at start.
import fs from 'fs'
import path from 'path'
const here = path.dirname(new URL(import.meta.url).pathname)
const ui = fs.readFileSync(path.join(here, '..', 'src', 'ui', 'index.html'), 'utf8')
const mdir = path.join(here, 'node_modules', 'pearcore', 'migrations')
const migrations = {}
for (const f of fs.readdirSync(mdir)) if (f.endsWith('.sql')) migrations[f] = fs.readFileSync(path.join(mdir, f), 'utf8')
migrations['meta/_journal.json'] = fs.readFileSync(path.join(mdir, 'meta', '_journal.json'), 'utf8')
const jsqr = fs.existsSync(path.join(here, '..', 'src', 'ui', 'jsQR.js')) ? fs.readFileSync(path.join(here, '..', 'src', 'ui', 'jsQR.js'), 'utf8') : ''

// The projects shell (rKeyChat app/, built with Vite into app/dist): text files as text, fonts as base64.
// Taken from ../app/dist (a copy in this repo) or, failing that, the desktop checkout beside it.
const app = {}
const distDirs = [path.join(here, '..', 'app', 'dist'), path.join(here, '..', '..', 'rKeyChat', 'app', 'dist')]
const dist = distDirs.find((d) => fs.existsSync(path.join(d, 'index.html')))
if (dist) {
  const walk = (dir, rel = '') => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name); const r = rel ? `${rel}/${e.name}` : e.name
      if (e.isDirectory()) { walk(p, r); continue }
      if (/\.(woff2?|ttf|otf|png|jpe?g|ico|webp)$/i.test(e.name)) app[r] = { b64: fs.readFileSync(p).toString('base64') }
      else app[r] = { text: fs.readFileSync(p, 'utf8') }
    }
  }
  walk(dist)
}
fs.writeFileSync(path.join(here, 'assets.js'), `// generated by build-assets.js\nexport default ${JSON.stringify({ ui, jsqr, migrations, app })}\n`)
const appBytes = Object.values(app).reduce((n, f) => n + (f.text?.length ?? f.b64.length), 0)
console.log(`assets.js: ui ${ui.length}B, ${Object.keys(migrations).length} migration files, shell ${dist ? `${Object.keys(app).length} files (${Math.round(appBytes / 1024)} KB) from ${dist}` : 'not found (app/dist): the phone gets the old page only'}`)
