// (Node) Embed the files the backend reads from disk (the web UI, pearcore's
// SQL migrations) into assets.js, so a bundled app can write them out at start.
import fs from 'fs'
import path from 'path'
const here = path.dirname(new URL(import.meta.url).pathname)
const ui = fs.readFileSync(path.join(here, '..', 'src', 'ui', 'index.html'), 'utf8')
const mdir = path.join(here, 'node_modules', 'pearcore', 'migrations')
const migrations = {}
for (const f of fs.readdirSync(mdir)) if (f.endsWith('.sql')) migrations[f] = fs.readFileSync(path.join(mdir, f), 'utf8')
migrations['meta/_journal.json'] = fs.readFileSync(path.join(mdir, 'meta', '_journal.json'), 'utf8')
const jsqr = fs.existsSync(path.join(here, '..', 'src', 'ui', 'jsQR.js')) ? fs.readFileSync(path.join(here, '..', 'src', 'ui', 'jsQR.js'), 'utf8') : ''
fs.writeFileSync(path.join(here, 'assets.js'), `// generated by build-assets.js\nexport default ${JSON.stringify({ ui, jsqr, migrations })}\n`)
console.log(`assets.js: ui ${ui.length}B, ${Object.keys(migrations).length} migration files`)
